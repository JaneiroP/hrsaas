-- ============================================================================
-- Módulo org — estructura organizacional (Fase 1).
--
-- Base de contracts: un contrato se firma con una company, no con el tenant
-- directamente. Todas las tablas llevan tenant_id (AD-02): org no tiene
-- ninguna tabla global.
-- ============================================================================

CREATE TABLE companies (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT       NOT NULL REFERENCES tenants (id),
    legal_name VARCHAR(200) NOT NULL,
    trade_name VARCHAR(200),
    rnc        VARCHAR(11)  NOT NULL,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- Sin validacion de digito verificador: pendiente de confirmar el
    -- algoritmo con un contador dominicano.
    CONSTRAINT uk_companies_rnc UNIQUE (tenant_id, rnc)
);

CREATE TABLE locations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT      NOT NULL REFERENCES tenants (id),
    company_id BIGINT      NOT NULL REFERENCES companies (id),
    name       VARCHAR(160) NOT NULL,
    address    VARCHAR(300),
    active     BOOLEAN     NOT NULL DEFAULT TRUE
);
CREATE INDEX ix_locations_company ON locations (tenant_id, company_id);

CREATE TABLE departments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT       NOT NULL REFERENCES tenants (id),
    company_id BIGINT       NOT NULL REFERENCES companies (id),
    name       VARCHAR(160) NOT NULL,
    active     BOOLEAN      NOT NULL DEFAULT TRUE
    -- Plano a proposito: sin parent_id. Añadir jerarquia despues es un
    -- cambio aditivo, no uno disruptivo.
);
CREATE INDEX ix_departments_company ON departments (tenant_id, company_id);

CREATE TABLE pay_grades (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT        NOT NULL REFERENCES tenants (id),
    company_id BIGINT        NOT NULL REFERENCES companies (id),
    code       VARCHAR(32)   NOT NULL,
    name       VARCHAR(160)  NOT NULL,
    min_salary NUMERIC(15,2) NOT NULL,
    max_salary NUMERIC(15,2) NOT NULL,
    currency   VARCHAR(3)    NOT NULL DEFAULT 'DOP',
    active     BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_pay_grades_company_code UNIQUE (tenant_id, company_id, code),
    CONSTRAINT ck_pay_grades_range CHECK (max_salary >= min_salary)
);

CREATE TABLE positions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT       NOT NULL REFERENCES tenants (id),
    company_id    BIGINT       NOT NULL REFERENCES companies (id),
    department_id BIGINT       NOT NULL REFERENCES departments (id),
    title         VARCHAR(160) NOT NULL,
    pay_grade_id  BIGINT       REFERENCES pay_grades (id),
    active        BOOLEAN      NOT NULL DEFAULT TRUE
);
CREATE INDEX ix_positions_company    ON positions (tenant_id, company_id);
CREATE INDEX ix_positions_department ON positions (tenant_id, department_id);

CREATE TABLE cost_centers (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT       NOT NULL REFERENCES tenants (id),
    company_id BIGINT       NOT NULL REFERENCES companies (id),
    code       VARCHAR(32)  NOT NULL,
    name       VARCHAR(160) NOT NULL,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_cost_centers_company_code UNIQUE (tenant_id, company_id, code)
);
