-- ============================================================================
-- Módulo contracts — vínculo laboral con vigencia (Fase 1).
--
-- employee_id/company_id/position_id/cost_center_id/supervisor_employee_id
-- son FK reales a tablas de otros módulos (org, people), pero la entidad
-- JPA los mapea como Long sueltos, nunca @ManyToOne cruzando el módulo — la
-- integridad referencial vive aqui, en SQL, no en el mapeo de Hibernate.
-- ============================================================================

CREATE TABLE employment_contracts (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id              BIGINT      NOT NULL REFERENCES tenants (id),
    employee_id            BIGINT      NOT NULL REFERENCES employees (id),
    company_id             BIGINT      NOT NULL REFERENCES companies (id),
    position_id            BIGINT      NOT NULL REFERENCES positions (id),
    cost_center_id         BIGINT      REFERENCES cost_centers (id),
    supervisor_employee_id BIGINT      REFERENCES employees (id),
    contract_type          VARCHAR(20) NOT NULL,
    start_date             DATE        NOT NULL,
    end_date               DATE,
    probation_ends_at      DATE,
    status                 VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_employment_contracts_type   CHECK (contract_type IN
        ('INDEFINITE', 'FIXED_TERM', 'PROJECT_BASED', 'INTERNSHIP')),
    CONSTRAINT ck_employment_contracts_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'TERMINATED'))
);
CREATE INDEX ix_employment_contracts_employee ON employment_contracts (tenant_id, employee_id);
CREATE INDEX ix_employment_contracts_company  ON employment_contracts (tenant_id, company_id);

-- Un solo contrato no-terminado por empleado, a nivel de TENANT, no de
-- company: si el negocio permite empleo simultaneo en dos razones sociales
-- del mismo tenant (frecuente en holdings), este indice es demasiado
-- estricto -- riesgo #1 documentado en el plan, decision del usuario si hace
-- falta relajarlo a (tenant_id, company_id, employee_id).
CREATE UNIQUE INDEX uk_employment_contracts_active_per_employee
    ON employment_contracts (tenant_id, employee_id)
    WHERE status <> 'TERMINATED';

-- Sin baseSalary en employment_contracts a proposito: esta tabla es la unica
-- fuente del salario. Duplicarlo en el contrato crearia una segunda fuente
-- de verdad.
CREATE TABLE salary_history (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      BIGINT        NOT NULL REFERENCES tenants (id),
    contract_id    BIGINT        NOT NULL REFERENCES employment_contracts (id),
    amount         NUMERIC(15,2) NOT NULL,
    currency       VARCHAR(3)    NOT NULL DEFAULT 'DOP',
    effective_from DATE          NOT NULL,
    effective_to   DATE,
    reason         VARCHAR(20)   NOT NULL,
    CONSTRAINT ck_salary_history_reason CHECK (reason IN
        ('HIRE', 'RAISE', 'PROMOTION', 'DEMOTION', 'CORRECTION', 'ADJUSTMENT'))
);
CREATE INDEX ix_salary_history_contract ON salary_history (tenant_id, contract_id);

-- Como mucho un registro de salario abierto por contrato.
CREATE UNIQUE INDEX uk_salary_history_open
    ON salary_history (tenant_id, contract_id)
    WHERE effective_to IS NULL;

-- Ledger append-only: cambios que no terminan el contrato (promocion, cambio
-- de cargo, de supervisor...). Sin @Audited en la entidad: ya es append-only
-- por diseño, auditar una auditoria no aporta nada.
CREATE TABLE contract_amendments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT      NOT NULL REFERENCES tenants (id),
    contract_id     BIGINT      NOT NULL REFERENCES employment_contracts (id),
    amendment_type  VARCHAR(20) NOT NULL,
    effective_date  DATE        NOT NULL,
    detail          JSONB       NOT NULL,
    notes           VARCHAR(500),
    CONSTRAINT ck_contract_amendments_type CHECK (amendment_type IN
        ('PROMOTION', 'POSITION_CHANGE', 'SUPERVISOR_CHANGE', 'SCHEDULE_CHANGE', 'COMPANY_TRANSFER', 'OTHER'))
);
CREATE INDEX ix_contract_amendments_contract ON contract_amendments (tenant_id, contract_id);

-- TerminationCause: provisional, sin validar legalmente. Confirmar con
-- abogado laboral/contador antes de que taxconfig/payroll decidan que
-- causal dispara cesantia/preaviso.
CREATE TABLE terminations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           BIGINT      NOT NULL REFERENCES tenants (id),
    contract_id         BIGINT      NOT NULL REFERENCES employment_contracts (id),
    termination_date    DATE        NOT NULL,
    cause               VARCHAR(24) NOT NULL,
    notice_given        BOOLEAN     NOT NULL DEFAULT FALSE,
    severance_eligible  BOOLEAN     NOT NULL DEFAULT FALSE,
    notes               VARCHAR(500),
    CONSTRAINT uk_terminations_contract UNIQUE (contract_id),
    CONSTRAINT ck_terminations_cause CHECK (cause IN
        ('RESIGNATION', 'JUSTIFIED_DISMISSAL', 'UNJUSTIFIED_DISMISSAL', 'MUTUAL_AGREEMENT',
         'CONTRACT_EXPIRATION', 'DEATH'))
);
CREATE INDEX ix_terminations_tenant ON terminations (tenant_id);
