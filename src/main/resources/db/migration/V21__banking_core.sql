-- ============================================================================
-- Módulo banking — lotes de pago (Fase 4). Por tenant, con RLS estándar.
-- ============================================================================

CREATE TABLE payment_batches (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id            BIGINT       NOT NULL REFERENCES tenants (id),
    payroll_run_id       BIGINT       NOT NULL REFERENCES payroll_runs (id),
    company_id           BIGINT       NOT NULL REFERENCES companies (id),
    bank_name            VARCHAR(160) NOT NULL,
    origin_account_number VARCHAR(60) NOT NULL,
    status               VARCHAR(16)  NOT NULL DEFAULT 'CONSTRUIDO',
    total_amount         NUMERIC(15,2) NOT NULL,
    currency             VARCHAR(3)   NOT NULL,
    built_by_user_id     BIGINT       NOT NULL,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    approved_by_user_id  BIGINT,
    approved_at          TIMESTAMPTZ,
    exported_at          TIMESTAMPTZ,
    sent_at              TIMESTAMPTZ,
    reconciled_at        TIMESTAMPTZ,
    CONSTRAINT ck_payment_batches_status CHECK (
        status IN ('CONSTRUIDO', 'VALIDADO', 'APROBADO', 'EXPORTADO', 'ENVIADO', 'CONCILIADO')
    )
);
CREATE INDEX ix_payment_batches_run     ON payment_batches (tenant_id, payroll_run_id);
CREATE INDEX ix_payment_batches_company ON payment_batches (tenant_id, company_id);

CREATE TABLE payment_batch_items (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         BIGINT      NOT NULL REFERENCES tenants (id),
    payment_batch_id  BIGINT      NOT NULL REFERENCES payment_batches (id),
    employee_id       BIGINT      NOT NULL REFERENCES employees (id),
    contract_id       BIGINT      NOT NULL REFERENCES employment_contracts (id),
    bank_account_id   BIGINT REFERENCES bank_accounts (id),
    amount            NUMERIC(15,2) NOT NULL,
    status            VARCHAR(16) NOT NULL DEFAULT 'PENDIENTE',
    rejection_code    VARCHAR(40),
    rejection_reason  VARCHAR(200),
    CONSTRAINT ck_payment_batch_items_status CHECK (status IN ('PENDIENTE', 'ACEPTADO', 'RECHAZADO'))
);
CREATE INDEX ix_payment_batch_items_batch ON payment_batch_items (tenant_id, payment_batch_id);
