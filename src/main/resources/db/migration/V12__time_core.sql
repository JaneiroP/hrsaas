-- Módulo time — feriados, licencias, horarios y marcajes (Fase 2).
--
-- employee_id/company_id/location_id son FK reales a otros módulos, mapeados
-- como Long sueltos en la entidad JPA -- mismo patron que contracts: la
-- integridad referencial vive aqui, no en el mapeo de Hibernate.
