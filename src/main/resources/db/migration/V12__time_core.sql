CREATE TABLE holiday_calendars (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT       NOT NULL REFERENCES tenants (id),
    company_id  BIGINT       NOT NULL REFERENCES companies (id),
    location_id BIGINT       REFERENCES locations (id),
    name        VARCHAR(160) NOT NULL
);
CREATE INDEX ix_holiday_calendars_company ON holiday_calendars (tenant_id, company_id);

CREATE TABLE holidays (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          BIGINT       NOT NULL REFERENCES tenants (id),
    holiday_calendar_id BIGINT      NOT NULL REFERENCES holiday_calendars (id),
    date               DATE         NOT NULL,
    name               VARCHAR(160) NOT NULL
);
CREATE INDEX ix_holidays_calendar_date ON holidays (tenant_id, holiday_calendar_id, date);

CREATE TABLE leave_types (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id             BIGINT       NOT NULL REFERENCES tenants (id),
    code                  VARCHAR(32)  NOT NULL,
    name                  VARCHAR(160) NOT NULL,
    paid                  BOOLEAN      NOT NULL,
    requires_approval     BOOLEAN      NOT NULL DEFAULT TRUE,
    accrual_days_per_year NUMERIC(6,2),
    max_carryover_days    INTEGER,
    active                BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_leave_types_code UNIQUE (tenant_id, code)
);

CREATE TABLE leave_balances (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      BIGINT        NOT NULL REFERENCES tenants (id),
    employee_id    BIGINT        NOT NULL REFERENCES employees (id),
    leave_type_id  BIGINT        NOT NULL REFERENCES leave_types (id),
    accrued_days   NUMERIC(6,2)  NOT NULL DEFAULT 0,
    used_days      NUMERIC(6,2)  NOT NULL DEFAULT 0,
    available_days NUMERIC(6,2)  NOT NULL DEFAULT 0,
    CONSTRAINT uk_leave_balances UNIQUE (tenant_id, employee_id, leave_type_id)
);

CREATE TABLE leave_requests (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         BIGINT       NOT NULL REFERENCES tenants (id),
    employee_id       BIGINT       NOT NULL REFERENCES employees (id),
    leave_type_id     BIGINT       NOT NULL REFERENCES leave_types (id),
    start_date        DATE         NOT NULL,
    end_date          DATE         NOT NULL,
    days              NUMERIC(6,2) NOT NULL,
    status            VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    reason            VARCHAR(500),
    requested_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    decided_by_user_id BIGINT,
    decided_at        TIMESTAMPTZ,
    CONSTRAINT ck_leave_requests_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_leave_requests_dates  CHECK (end_date >= start_date)
);
CREATE INDEX ix_leave_requests_employee ON leave_requests (tenant_id, employee_id);

CREATE TABLE work_schedules (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      BIGINT       NOT NULL REFERENCES tenants (id),
    company_id     BIGINT       NOT NULL REFERENCES companies (id),
    name           VARCHAR(160) NOT NULL,
    monday_hours   NUMERIC(4,2) NOT NULL DEFAULT 0,
    tuesday_hours  NUMERIC(4,2) NOT NULL DEFAULT 0,
    wednesday_hours NUMERIC(4,2) NOT NULL DEFAULT 0,
    thursday_hours NUMERIC(4,2) NOT NULL DEFAULT 0,
    friday_hours   NUMERIC(4,2) NOT NULL DEFAULT 0,
    saturday_hours NUMERIC(4,2) NOT NULL DEFAULT 0,
    sunday_hours   NUMERIC(4,2) NOT NULL DEFAULT 0,
    active         BOOLEAN      NOT NULL DEFAULT TRUE
);
CREATE INDEX ix_work_schedules_company ON work_schedules (tenant_id, company_id);

CREATE TABLE employee_work_schedules (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         BIGINT NOT NULL REFERENCES tenants (id),
    employee_id       BIGINT NOT NULL REFERENCES employees (id),
    work_schedule_id  BIGINT NOT NULL REFERENCES work_schedules (id),
    effective_from    DATE   NOT NULL,
    effective_to      DATE
);
CREATE INDEX ix_employee_work_schedules_employee ON employee_work_schedules (tenant_id, employee_id);

-- Como mucho una asignación de horario vigente por empleado.
CREATE UNIQUE INDEX uk_employee_work_schedules_open
    ON employee_work_schedules (tenant_id, employee_id)
    WHERE effective_to IS NULL;

-- AD-11: idempotente por (tenant, empleado, dispositivo, momento) -- NULL en
-- device_id (marcaje MANUAL) no se compara como igual a otro NULL en
-- Postgres, asi que esta restriccion solo protege marcajes con dispositivo,
-- que es exactamente donde un reintento de webhook puede duplicar.
CREATE TABLE time_entries (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT      NOT NULL REFERENCES tenants (id),
    employee_id BIGINT      NOT NULL REFERENCES employees (id),
    type        VARCHAR(16) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    source      VARCHAR(16) NOT NULL,
    device_id   VARCHAR(100),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_time_entries_type   CHECK (type IN ('CLOCK_IN', 'CLOCK_OUT', 'BREAK_START', 'BREAK_END')),
    CONSTRAINT ck_time_entries_source CHECK (source IN ('BIOMETRIC', 'MANUAL', 'IMPORT')),
    CONSTRAINT uk_time_entries_device UNIQUE (tenant_id, employee_id, device_id, occurred_at)
);
CREATE INDEX ix_time_entries_employee_time ON time_entries (tenant_id, employee_id, occurred_at);
