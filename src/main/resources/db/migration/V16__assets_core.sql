-- ============================================================================
-- Módulo assets — inventario de equipos (Fase 2).
-- ============================================================================

CREATE TABLE assets (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      BIGINT        NOT NULL REFERENCES tenants (id),
    company_id     BIGINT        NOT NULL REFERENCES companies (id),
    asset_tag      VARCHAR(64)   NOT NULL,
    name           VARCHAR(160)  NOT NULL,
    category       VARCHAR(80),
    serial_number  VARCHAR(100),
    purchase_date  DATE,
    value          NUMERIC(15,2),
    status         VARCHAR(16)   NOT NULL DEFAULT 'AVAILABLE',
    CONSTRAINT uk_assets_tag UNIQUE (tenant_id, asset_tag),
    CONSTRAINT ck_assets_status CHECK (status IN ('AVAILABLE', 'ASSIGNED', 'RETIRED'))
);
CREATE INDEX ix_assets_company ON assets (tenant_id, company_id);

CREATE TABLE asset_assignments (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id                   BIGINT      NOT NULL REFERENCES tenants (id),
    asset_id                    BIGINT      NOT NULL REFERENCES assets (id),
    employee_id                 BIGINT      NOT NULL REFERENCES employees (id),
    assigned_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),
    returned_at                 TIMESTAMPTZ,
    acknowledgement_document_key VARCHAR(500),
    status                      VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT ck_asset_assignments_status CHECK (status IN ('ACTIVE', 'RETURNED'))
);
CREATE INDEX ix_asset_assignments_employee ON asset_assignments (tenant_id, employee_id);
CREATE INDEX ix_asset_assignments_asset    ON asset_assignments (tenant_id, asset_id);

-- Como mucho una asignacion activa por equipo a la vez.
CREATE UNIQUE INDEX uk_asset_assignments_active
    ON asset_assignments (tenant_id, asset_id)
    WHERE status = 'ACTIVE';

CREATE TABLE asset_returns (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           BIGINT      NOT NULL REFERENCES tenants (id),
    asset_assignment_id BIGINT      NOT NULL REFERENCES asset_assignments (id),
    returned_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    condition           VARCHAR(16) NOT NULL,
    notes               VARCHAR(500),
    document_key        VARCHAR(500),
    CONSTRAINT uk_asset_returns_assignment UNIQUE (asset_assignment_id),
    CONSTRAINT ck_asset_returns_condition CHECK (condition IN ('GOOD', 'DAMAGED', 'LOST'))
);
