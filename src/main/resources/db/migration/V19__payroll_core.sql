-- ============================================================================
-- Módulo payroll — el motor de nómina (Fase 3). Todas las tablas son por
-- tenant, a diferencia de taxconfig (V18): la corrida y sus volantes son
-- datos de negocio del tenant, no configuración fiscal compartida.
-- ============================================================================

CREATE TABLE payroll_periods (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT       NOT NULL REFERENCES tenants (id),
    company_id BIGINT       NOT NULL REFERENCES companies (id),
    name       VARCHAR(80)  NOT NULL,
    frequency  VARCHAR(16)  NOT NULL,
    start_date DATE         NOT NULL,
    end_date   DATE         NOT NULL,
    pay_date   DATE         NOT NULL,
    CONSTRAINT ck_payroll_periods_frequency CHECK (frequency IN ('MONTHLY', 'BIWEEKLY'))
);
CREATE INDEX ix_payroll_periods_company ON payroll_periods (tenant_id, company_id);

CREATE TABLE payroll_runs (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           BIGINT      NOT NULL REFERENCES tenants (id),
    payroll_period_id   BIGINT      NOT NULL REFERENCES payroll_periods (id),
    company_id          BIGINT      NOT NULL REFERENCES companies (id),
    status              VARCHAR(16) NOT NULL DEFAULT 'BORRADOR',
    config_version_id   VARCHAR(100),
    reversal_of_run_id  BIGINT REFERENCES payroll_runs (id),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    calculated_at       TIMESTAMPTZ,
    approved_at         TIMESTAMPTZ,
    approved_by_user_id BIGINT,
    paid_at             TIMESTAMPTZ,
    closed_at           TIMESTAMPTZ,
    CONSTRAINT ck_payroll_runs_status CHECK (
        status IN ('BORRADOR', 'CALCULADA', 'EN_REVISION', 'APROBADA', 'PAGADA', 'CERRADA', 'ANULADA')
    )
);
CREATE INDEX ix_payroll_runs_period  ON payroll_runs (tenant_id, payroll_period_id);
CREATE INDEX ix_payroll_runs_company ON payroll_runs (tenant_id, company_id);

CREATE TABLE payroll_concepts (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           BIGINT      NOT NULL REFERENCES tenants (id),
    code                VARCHAR(32)  NOT NULL,
    name                VARCHAR(160) NOT NULL,
    type                VARCHAR(24)  NOT NULL,
    execution_order     INTEGER      NOT NULL,
    taxable_for_isr     BOOLEAN      NOT NULL DEFAULT false,
    contributes_to_tss  BOOLEAN      NOT NULL DEFAULT false,
    affects_regalia     BOOLEAN      NOT NULL DEFAULT false,
    formula_strategy    VARCHAR(24)  NOT NULL,
    formula_params      JSONB        NOT NULL,
    active              BOOLEAN      NOT NULL DEFAULT true,
    CONSTRAINT uk_payroll_concepts_code UNIQUE (tenant_id, code),
    CONSTRAINT ck_payroll_concepts_type CHECK (
        type IN ('EARNING', 'DEDUCTION', 'EMPLOYER_CONTRIBUTION', 'PROVISION')
    ),
    CONSTRAINT ck_payroll_concepts_formula_strategy CHECK (
        formula_strategy IN ('FIXED', 'RATE_OF_BASE', 'HOURS_TIMES_RATE', 'BRACKET_TABLE')
    )
);

CREATE TABLE payslips (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      BIGINT      NOT NULL REFERENCES tenants (id),
    payroll_run_id BIGINT      NOT NULL REFERENCES payroll_runs (id),
    employee_id    BIGINT      NOT NULL REFERENCES employees (id),
    contract_id    BIGINT      NOT NULL REFERENCES employment_contracts (id),
    gross_pay      NUMERIC(15,2) NOT NULL,
    net_pay        NUMERIC(15,2) NOT NULL,
    currency       VARCHAR(3)  NOT NULL
);
CREATE INDEX ix_payslips_run      ON payslips (tenant_id, payroll_run_id);
CREATE INDEX ix_payslips_employee ON payslips (tenant_id, employee_id);

CREATE TABLE payslip_lines (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          BIGINT       NOT NULL REFERENCES tenants (id),
    payslip_id         BIGINT       NOT NULL REFERENCES payslips (id),
    payroll_concept_id BIGINT REFERENCES payroll_concepts (id),
    description        VARCHAR(160) NOT NULL,
    type               VARCHAR(24)  NOT NULL,
    amount             NUMERIC(15,2) NOT NULL,
    line_order         INTEGER      NOT NULL,
    CONSTRAINT ck_payslip_lines_type CHECK (
        type IN ('EARNING', 'DEDUCTION', 'EMPLOYER_CONTRIBUTION', 'PROVISION')
    )
);
CREATE INDEX ix_payslip_lines_payslip ON payslip_lines (tenant_id, payslip_id);

CREATE TABLE accruals (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      BIGINT      NOT NULL REFERENCES tenants (id),
    payroll_run_id BIGINT      NOT NULL REFERENCES payroll_runs (id),
    employee_id    BIGINT      NOT NULL REFERENCES employees (id),
    concept_code   VARCHAR(32) NOT NULL,
    type           VARCHAR(24) NOT NULL,
    amount         NUMERIC(15,2) NOT NULL,
    CONSTRAINT ck_accruals_type CHECK (type IN ('EMPLOYER_CONTRIBUTION', 'PROVISION'))
);
CREATE INDEX ix_accruals_run      ON accruals (tenant_id, payroll_run_id);
CREATE INDEX ix_accruals_employee ON accruals (tenant_id, employee_id);
