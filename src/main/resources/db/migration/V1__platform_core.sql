-- ============================================================================
-- Módulo platform — núcleo multi-tenant.
--
-- Reglas de pertenencia:
--   tenants, users, modules, permissions  -> globales (sin tenant_id)
--   el resto                              -> pertenece a un tenant
--
-- Un usuario es global y puede pertenecer a varios tenants (user_tenants).
-- Los roles son por tenant: "Supervisor" del tenant A no es el del tenant B.
-- ============================================================================

CREATE TABLE tenants (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug       VARCHAR(64)  NOT NULL,
    name       VARCHAR(160) NOT NULL,
    status     VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_tenants_slug   UNIQUE (slug),
    CONSTRAINT ck_tenants_status CHECK (status IN ('PENDING', 'ACTIVE', 'SUSPENDED'))
);

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(160) NOT NULL,
    password_hash   VARCHAR(100),
    full_name       VARCHAR(160) NOT NULL,
    enabled         BOOLEAN      NOT NULL DEFAULT TRUE,
    locked          BOOLEAN      NOT NULL DEFAULT FALSE,
    failed_attempts SMALLINT     NOT NULL DEFAULT 0,
    last_login_at   TIMESTAMPTZ,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- email se normaliza a minúsculas en la aplicación antes de persistir
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE user_tenants (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT      NOT NULL REFERENCES tenants (id),
    user_id   BIGINT      NOT NULL REFERENCES users (id),
    status    VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    joined_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_user_tenants        UNIQUE (tenant_id, user_id),
    CONSTRAINT ck_user_tenants_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'REVOKED'))
);
CREATE INDEX ix_user_tenants_user ON user_tenants (user_id);

-- Catálogo global de módulos funcionales. Solo da integridad referencial al
-- catálogo de permisos; no se mapea como entidad.
CREATE TABLE modules (
    code VARCHAR(32) PRIMARY KEY,
    name VARCHAR(80) NOT NULL
);

-- Catálogo global de permisos. No es configurable por tenant: lo que el tenant
-- configura es qué rol recibe cuál permiso y con qué alcance.
--
-- max_scope acota el alcance concedible. 'payslip:read_own' no debe poder
-- otorgarse a nivel COMPANY por más que alguien lo intente desde la API.
CREATE TABLE permissions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(64)  NOT NULL,
    module_code VARCHAR(32)  NOT NULL REFERENCES modules (code),
    description VARCHAR(200) NOT NULL,
    max_scope   VARCHAR(16)  NOT NULL DEFAULT 'ALL',
    CONSTRAINT uk_permissions_code      UNIQUE (code),
    CONSTRAINT ck_permissions_max_scope CHECK (max_scope IN ('SELF', 'TEAM', 'COMPANY', 'ALL'))
);

CREATE TABLE roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT      NOT NULL REFERENCES tenants (id),
    name        VARCHAR(64) NOT NULL,
    description VARCHAR(200),
    system_role BOOLEAN     NOT NULL DEFAULT FALSE,
    active      BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_roles_tenant_name UNIQUE (tenant_id, name)
);

-- El alcance vive en la CONCESIÓN, no en el rol. Un mismo rol "Supervisor"
-- puede leer empleados con alcance TEAM y volantes con alcance SELF.
CREATE TABLE role_permissions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT      NOT NULL REFERENCES tenants (id),
    role_id       BIGINT      NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    permission_id BIGINT      NOT NULL REFERENCES permissions (id),
    scope         VARCHAR(16) NOT NULL,
    CONSTRAINT uk_role_permissions       UNIQUE (role_id, permission_id),
    CONSTRAINT ck_role_permissions_scope CHECK (scope IN ('SELF', 'TEAM', 'COMPANY', 'ALL'))
);
CREATE INDEX ix_role_permissions_role ON role_permissions (tenant_id, role_id);

CREATE TABLE user_roles (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT      NOT NULL REFERENCES tenants (id),
    user_id    BIGINT      NOT NULL REFERENCES users (id),
    role_id    BIGINT      NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    granted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_user_roles UNIQUE (tenant_id, user_id, role_id)
);
CREATE INDEX ix_user_roles_user ON user_roles (tenant_id, user_id);

-- Se guarda el SHA-256 del token, nunca el token. Si te roban la base de datos
-- no pueden aceptar invitaciones pendientes.
CREATE TABLE invitations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT       NOT NULL REFERENCES tenants (id),
    email       VARCHAR(160) NOT NULL,
    role_id     BIGINT       NOT NULL REFERENCES roles (id),
    token_hash  VARCHAR(64)  NOT NULL,
    status      VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    invited_by  BIGINT       REFERENCES users (id),
    expires_at  TIMESTAMPTZ  NOT NULL,
    accepted_at TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_invitations_token  UNIQUE (token_hash),
    CONSTRAINT ck_invitations_status CHECK (status IN ('PENDING', 'ACCEPTED', 'EXPIRED', 'REVOKED'))
);

-- Índice parcial: una sola invitación pendiente por email y tenant. Reinvitar
-- exige revocar la anterior, así no quedan dos tokens válidos circulando.
CREATE UNIQUE INDEX uk_invitations_pending
    ON invitations (tenant_id, email)
    WHERE status = 'PENDING';

-- Append-only: registra LECTURAS de datos sensibles, no solo cambios (AD-07).
-- Envers cubre el "quién lo cambió"; esto cubre el "quién lo vio".
CREATE TABLE audit_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT      NOT NULL REFERENCES tenants (id),
    actor_user_id BIGINT      REFERENCES users (id),
    action        VARCHAR(64) NOT NULL,
    resource      VARCHAR(64) NOT NULL,
    resource_id   VARCHAR(64),
    detail        JSONB,
    occurred_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_audit_events_tenant_time ON audit_events (tenant_id, occurred_at DESC);
