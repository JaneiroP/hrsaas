-- ============================================================================
-- Módulo integrations — conectores de asistencia.
--
-- Un conector es el extremo por el que un sistema externo de control de
-- asistencia entrega marcajes por webhook. Solo existe esta pieza del módulo
-- que describe el blueprint (§08): API keys, outbox y webhooks salientes
-- quedan fuera de alcance.
-- ============================================================================

CREATE TABLE attendance_connectors (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT       NOT NULL REFERENCES tenants (id),
    -- Lo que viaja en la URL del webhook. Aleatorio y no el id secuencial: la
    -- URL la configura alguien en otro sistema y acaba en sus logs.
    public_id        UUID         NOT NULL,
    name             VARCHAR(160) NOT NULL,
    -- Cifrado en columna (AD-08), no un hash: verificar un HMAC exige el
    -- secreto. Nulo hasta que el administrador lo registra; mientras tanto el
    -- conector rechaza todo lo que reciba.
    signing_secret   VARCHAR(255),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_received_at TIMESTAMPTZ,
    CONSTRAINT uk_attendance_connectors_public_id UNIQUE (public_id)
);
CREATE INDEX ix_attendance_connectors_tenant ON attendance_connectors (tenant_id);
