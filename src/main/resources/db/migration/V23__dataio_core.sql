-- ============================================================================
-- Módulo dataio — motor único de importación (Fase 4, blueprint §07).
-- ============================================================================

CREATE TABLE import_batches (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         BIGINT      NOT NULL REFERENCES tenants (id),
    import_type       VARCHAR(40) NOT NULL,
    file_name         VARCHAR(255) NOT NULL,
    file_hash         CHAR(64)    NOT NULL,
    status            VARCHAR(16) NOT NULL DEFAULT 'STAGED',
    total_rows        INTEGER     NOT NULL DEFAULT 0,
    valid_rows        INTEGER     NOT NULL DEFAULT 0,
    error_rows        INTEGER     NOT NULL DEFAULT 0,
    uploaded_by_user_id BIGINT    NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    validated_at      TIMESTAMPTZ,
    committed_at      TIMESTAMPTZ,
    CONSTRAINT uk_import_batches_hash UNIQUE (tenant_id, file_hash),
    CONSTRAINT ck_import_batches_status CHECK (status IN ('STAGED', 'VALIDATED', 'COMMITTED'))
);

CREATE TABLE import_rows (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT      NOT NULL REFERENCES tenants (id),
    import_batch_id BIGINT      NOT NULL REFERENCES import_batches (id),
    line_number     INTEGER     NOT NULL,
    raw_data        JSONB       NOT NULL,
    status          VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    errors          JSONB,
    CONSTRAINT ck_import_rows_status CHECK (status IN ('PENDING', 'VALID', 'INVALID'))
);
CREATE INDEX ix_import_rows_batch ON import_rows (tenant_id, import_batch_id);
