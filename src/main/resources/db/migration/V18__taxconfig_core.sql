-- ============================================================================
-- Módulo taxconfig — reglas fiscales y laborales con vigencia por fecha (AD-04).
--
-- GLOBAL: sin tenant_id, sin RLS. La ley dominicana es la misma para todas
-- las empresas del pais -- mismo tratamiento que 'modules'/'permissions' en
-- V1__platform_core.sql, no el de las tablas de negocio del resto de la suite.
--
-- SIN DATOS SEMBRADOS A PROPOSITO. El blueprint de este proyecto trae tasas
-- de referencia (SFS 3.04%/7.09%, AFP 2.87%/7.10%, SRL ~1.1%, INFOTEP 1.00%/
-- 0.50%, escala de ISR) explicitamente marcadas como "para dimensionar el
-- modelo de datos, no para calcular nomina real" -- insertarlas aqui como
-- migracion las volveria parte permanente del historial de la base (una
-- migracion aplicada nunca se edita, regla del proyecto), mezclando datos no
-- validados con datos de produccion reales el dia que un contador dominicano
-- confirme las cifras vigentes. TaxConfigLookupServiceTest prueba el
-- mecanismo de vigencia por fecha con datos de prueba explicitos en el test,
-- no en esta migracion. La carga real de parametros fiscales validados sera
-- una migracion propia, posterior, cuando exista esa validacion.
-- ============================================================================

CREATE TABLE contribution_schemes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(32)   NOT NULL,
    name           VARCHAR(160)  NOT NULL,
    employee_rate  NUMERIC(7,4),
    employer_rate  NUMERIC(7,4),
    cap_amount     NUMERIC(15,2),
    effective_from DATE          NOT NULL,
    effective_to   DATE
);
CREATE INDEX ix_contribution_schemes_code ON contribution_schemes (code, effective_from);

-- Como mucho una fila abierta (vigente hasta hoy) por codigo.
CREATE UNIQUE INDEX uk_contribution_schemes_open
    ON contribution_schemes (code)
    WHERE effective_to IS NULL;

CREATE TABLE tax_brackets (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scheme_code    VARCHAR(32)   NOT NULL,
    bracket_order  INTEGER       NOT NULL,
    lower_bound    NUMERIC(15,2) NOT NULL,
    upper_bound    NUMERIC(15,2),
    rate           NUMERIC(7,4)  NOT NULL,
    effective_from DATE          NOT NULL,
    effective_to   DATE
);
CREATE INDEX ix_tax_brackets_scheme ON tax_brackets (scheme_code, effective_from, bracket_order);

CREATE TABLE statutory_parameters (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(64)   NOT NULL,
    description    VARCHAR(200)  NOT NULL,
    value          NUMERIC(15,4) NOT NULL,
    effective_from DATE          NOT NULL,
    effective_to   DATE
);
CREATE INDEX ix_statutory_parameters_code ON statutory_parameters (code, effective_from);

CREATE UNIQUE INDEX uk_statutory_parameters_open
    ON statutory_parameters (code)
    WHERE effective_to IS NULL;

CREATE TABLE severance_scales (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    min_months_of_service  INTEGER      NOT NULL,
    max_months_of_service  INTEGER,
    days_of_salary_per_year NUMERIC(6,2) NOT NULL,
    effective_from         DATE         NOT NULL,
    effective_to           DATE
);
CREATE INDEX ix_severance_scales_range ON severance_scales (effective_from, min_months_of_service);
