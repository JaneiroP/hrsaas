-- ============================================================================
-- Módulo people — expediente del empleado (Fase 1).
--
-- document_number/account_number van cifrados en la aplicación (AD-08,
-- AES-256-GCM); esta migración solo ve VARCHAR(255) porque el ciphertext en
-- Base64 no cabe en el tamaño de la columna en claro. La unicidad real la da
-- el indice ciego (*_hmac, CHAR(64) = SHA-256/HMAC-SHA256 en hexadecimal),
-- no la columna cifrada -- dos documentos iguales cifran distinto por el IV
-- aleatorio de cada operacion.
-- ============================================================================

CREATE TABLE employees (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           BIGINT       NOT NULL REFERENCES tenants (id),
    first_name          VARCHAR(100) NOT NULL,
    last_name           VARCHAR(100) NOT NULL,
    birth_date          DATE         NOT NULL,
    document_type       VARCHAR(16)  NOT NULL,
    document_number     VARCHAR(255) NOT NULL,
    document_number_hmac CHAR(64)    NOT NULL,
    email               VARCHAR(160),
    phone               VARCHAR(30),
    user_id             BIGINT,
    status              VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_employees_document_hmac UNIQUE (tenant_id, document_number_hmac),
    CONSTRAINT ck_employees_document_type CHECK (document_type IN ('CEDULA', 'PASSPORT')),
    CONSTRAINT ck_employees_status        CHECK (status IN ('PENDING', 'ACTIVE', 'INACTIVE'))
);
CREATE INDEX ix_employees_user ON employees (tenant_id, user_id);

CREATE TABLE employee_documents (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          BIGINT       NOT NULL REFERENCES tenants (id),
    employee_id        BIGINT       NOT NULL REFERENCES employees (id),
    category           VARCHAR(24)  NOT NULL,
    file_name          VARCHAR(255) NOT NULL,
    storage_key        VARCHAR(500) NOT NULL,
    content_type       VARCHAR(100) NOT NULL,
    size_bytes         BIGINT       NOT NULL,
    uploaded_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    uploaded_by_user_id BIGINT
);
CREATE INDEX ix_employee_documents_employee ON employee_documents (tenant_id, employee_id);

-- documentNumber SIN cifrar a proposito: fuera del alcance literal de AD-08.
-- Revisar si el negocio realmente captura cedula de dependientes menores.
CREATE TABLE dependents (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT       NOT NULL REFERENCES tenants (id),
    employee_id     BIGINT       NOT NULL REFERENCES employees (id),
    full_name       VARCHAR(200) NOT NULL,
    relationship    VARCHAR(16)  NOT NULL,
    birth_date      DATE         NOT NULL,
    document_number VARCHAR(255),
    CONSTRAINT ck_dependents_relationship CHECK (relationship IN ('SPOUSE', 'CHILD', 'PARENT', 'SIBLING', 'OTHER'))
);
CREATE INDEX ix_dependents_employee ON dependents (tenant_id, employee_id);

CREATE TABLE emergency_contacts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT       NOT NULL REFERENCES tenants (id),
    employee_id  BIGINT       NOT NULL REFERENCES employees (id),
    full_name    VARCHAR(200) NOT NULL,
    relationship VARCHAR(60),
    phone        VARCHAR(30)  NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_emergency_contacts_employee ON emergency_contacts (tenant_id, employee_id);

CREATE TABLE bank_accounts (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           BIGINT       NOT NULL REFERENCES tenants (id),
    employee_id         BIGINT       NOT NULL REFERENCES employees (id),
    bank_name           VARCHAR(160) NOT NULL,
    account_type        VARCHAR(16)  NOT NULL,
    account_number      VARCHAR(255) NOT NULL,
    account_number_hmac CHAR(64)     NOT NULL,
    is_primary          BOOLEAN      NOT NULL DEFAULT TRUE,
    active              BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_bank_accounts_number UNIQUE (tenant_id, account_number_hmac),
    CONSTRAINT ck_bank_accounts_type   CHECK (account_type IN ('SAVINGS', 'CHECKING'))
);
CREATE INDEX ix_bank_accounts_employee ON bank_accounts (tenant_id, employee_id);

-- Como mucho una cuenta primaria por empleado. Indice parcial, mismo patron
-- que uk_invitations_pending en V1__platform_core.sql.
CREATE UNIQUE INDEX uk_bank_accounts_primary
    ON bank_accounts (tenant_id, employee_id)
    WHERE is_primary = TRUE;
