CREATE TABLE loan_agreements (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           BIGINT        NOT NULL REFERENCES tenants (id),
    employee_id         BIGINT        NOT NULL REFERENCES employees (id),
    principal           NUMERIC(15,2) NOT NULL,
    installment_count   INTEGER       NOT NULL,
    installment_amount  NUMERIC(15,2) NOT NULL,
    start_date          DATE          NOT NULL,
    status              VARCHAR(16)   NOT NULL DEFAULT 'ACTIVE',
    description         VARCHAR(500),
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_loan_agreements_status CHECK (status IN ('ACTIVE', 'PAID_OFF', 'CANCELLED')),
    CONSTRAINT ck_loan_agreements_count  CHECK (installment_count > 0)
);
CREATE INDEX ix_loan_agreements_employee ON loan_agreements (tenant_id, employee_id);

CREATE TABLE loan_installments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           BIGINT        NOT NULL REFERENCES tenants (id),
    loan_agreement_id   BIGINT        NOT NULL REFERENCES loan_agreements (id),
    installment_number  INTEGER       NOT NULL,
    due_date            DATE          NOT NULL,
    amount              NUMERIC(15,2) NOT NULL,
    status              VARCHAR(16)   NOT NULL DEFAULT 'PENDING',
    paid_at             TIMESTAMPTZ,
    CONSTRAINT ck_loan_installments_status CHECK (status IN ('PENDING', 'PAID')),
    CONSTRAINT uk_loan_installments_number UNIQUE (tenant_id, loan_agreement_id, installment_number)
);
CREATE INDEX ix_loan_installments_due ON loan_installments (tenant_id, loan_agreement_id, due_date);

CREATE TABLE salary_advances (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      BIGINT        NOT NULL REFERENCES tenants (id),
    employee_id    BIGINT        NOT NULL REFERENCES employees (id),
    amount         NUMERIC(15,2) NOT NULL,
    request_date   DATE          NOT NULL,
    status         VARCHAR(16)   NOT NULL DEFAULT 'PENDING',
    deduction_date DATE,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_salary_advances_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'DEDUCTED'))
);
CREATE INDEX ix_salary_advances_employee ON salary_advances (tenant_id, employee_id);

-- Exactamente uno de fixed_amount/percentage debe llevar valor -- lo exige la
-- capa de aplicacion (GarnishmentService.create), no una CHECK: cual de los
-- dos aplica es una regla de negocio, no una restriccion de integridad.
CREATE TABLE garnishment_orders (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          BIGINT       NOT NULL REFERENCES tenants (id),
    employee_id        BIGINT       NOT NULL REFERENCES employees (id),
    court_order_number VARCHAR(100) NOT NULL,
    beneficiary        VARCHAR(200) NOT NULL,
    fixed_amount       NUMERIC(15,2),
    percentage         NUMERIC(5,2),
    priority           INTEGER      NOT NULL,
    start_date         DATE         NOT NULL,
    end_date           DATE,
    status             VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    notes              VARCHAR(500),
    CONSTRAINT ck_garnishment_orders_status CHECK (status IN ('ACTIVE', 'COMPLETED', 'CANCELLED'))
);
CREATE INDEX ix_garnishment_orders_employee_priority ON garnishment_orders (tenant_id, employee_id, priority);
